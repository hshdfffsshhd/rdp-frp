function Test-IsAdministrator {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($identity)
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Get-WindowsArchitecture {
    $arch = $env:PROCESSOR_ARCHITECTURE
    if ($env:PROCESSOR_ARCHITEW6432) { $arch = $env:PROCESSOR_ARCHITEW6432 }
    switch ($arch.ToUpperInvariant()) {
        "AMD64" { return "amd64" }
        "ARM64" { return "arm64" }
        "X86"   { return "386" }
        default { return "amd64" }
    }
}

function New-SecureRandomInt {
    param([Parameter(Mandatory)][int]$Maximum)
    if ($Maximum -le 0) { throw "Maximum must be greater than zero." }
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $bytes = New-Object byte[] 4
        $upperBound = 4294967296L
        $limit = $upperBound - ($upperBound % [long]$Maximum)
        do {
            $rng.GetBytes($bytes)
            $value = [long][BitConverter]::ToUInt32($bytes, 0)
        } while ($value -ge $limit)
        return [int]($value % [long]$Maximum)
    } finally {
        $rng.Dispose()
    }
}

function New-StrongPassword {
    param([int]$Length = 16)
    if ($Length -lt 16) { $Length = 16 }

    $sets = @(
        [char[]](65..90),                                           # A-Z
        [char[]](97..122),                                          # a-z
        [char[]](48..57),                                           # 0-9
        ([char[]](33..47) + [char[]](58..64) + [char[]](91..96) + [char[]](123..126))
    )

    $chars = New-Object System.Collections.Generic.List[char]
    foreach ($set in $sets) {
        for ($i = 0; $i -lt 4; $i++) {
            $chars.Add($set[(New-SecureRandomInt -Maximum $set.Count)])
        }
    }
    while ($chars.Count -lt $Length) {
        $set = $sets[(New-SecureRandomInt -Maximum $sets.Count)]
        $chars.Add($set[(New-SecureRandomInt -Maximum $set.Count)])
    }

    # Fisher-Yates shuffle so the character classes are not grouped.
    for ($i = $chars.Count - 1; $i -gt 0; $i--) {
        $j = New-SecureRandomInt -Maximum ($i + 1)
        $tmp = $chars[$i]
        $chars[$i] = $chars[$j]
        $chars[$j] = $tmp
    }
    return (-join $chars)
}

function ConvertTo-TomlString {
    param([Parameter(Mandatory)][AllowEmptyString()][string]$Value)
    return '"' + ($Value.Replace('\', '\\').Replace('"', '\"')) + '"'
}

function New-FrpcConfig {
    param(
        [Parameter(Mandatory)][string]$ServerAddr,
        [Parameter(Mandatory)][int]$ServerPort,
        [Parameter(Mandatory)][string]$ProxyName,
        [Parameter(Mandatory)][int]$LocalPort,
        [Parameter(Mandatory)][int]$RemotePort,
        [string]$Token = "",
        [bool]$UseEncryption = $true,
        [string]$LogLevel = "info"
    )

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("# Generated by rdp-frp - safe to delete, it is recreated on every start.")
    $lines.Add("serverAddr = " + (ConvertTo-TomlString $ServerAddr))
    $lines.Add("serverPort = $ServerPort")
    $lines.Add("")
    if ($Token) {
        $lines.Add("[auth]")
        $lines.Add('method = "token"')
        $lines.Add("token = " + (ConvertTo-TomlString $Token))
        $lines.Add("")
    }
    $lines.Add("[log]")
    $lines.Add('to = "console"')
    $lines.Add("level = " + (ConvertTo-TomlString $LogLevel))
    $lines.Add("")
    $lines.Add("[[proxies]]")
    $lines.Add("name = " + (ConvertTo-TomlString $ProxyName))
    $lines.Add('type = "tcp"')
    $lines.Add('localIP = "127.0.0.1"')
    $lines.Add("localPort = $LocalPort")
    $lines.Add("remotePort = $RemotePort")
    $lines.Add("transport.useEncryption = " + $UseEncryption.ToString().ToLowerInvariant())
    $lines.Add("transport.useCompression = false")
    return (($lines -join "`r`n") + "`r`n")
}

function Write-TextFileNoBom {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][AllowEmptyString()][string]$Content
    )
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $Content, $utf8)
}

function Read-StateFile {
    param([Parameter(Mandatory)][string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) {
        throw "State file not found: $Path. Run Start-FrpTunnel.ps1 first."
    }
    return (Get-Content -LiteralPath $Path -Raw | ConvertFrom-Json)
}

function Save-StateFile {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)]$State
    )
    Write-TextFileNoBom -Path $Path -Content ($State | ConvertTo-Json -Depth 6)
}

function Protect-Directory {
    param([Parameter(Mandatory)][string]$Path)
    if (-not (Test-IsAdministrator)) {
        Write-Warning "Skipping ACL hardening for ${Path}: the current process is not elevated."
        return
    }
    try {
        if (-not (Test-Path -LiteralPath $Path)) { return }
        $acl = New-Object System.Security.AccessControl.DirectorySecurity
        $acl.SetAccessRuleProtection($true, $false)
        $admins = New-Object System.Security.Principal.SecurityIdentifier("S-1-5-32-544")
        $system = New-Object System.Security.Principal.SecurityIdentifier("S-1-5-18")
        $inheritance = [System.Security.AccessControl.InheritanceFlags]"ContainerInherit, ObjectInherit"
        $propagation = [System.Security.AccessControl.PropagationFlags]::None
        $allow = [System.Security.AccessControl.AccessControlType]::Allow
        $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule($admins, "FullControl", $inheritance, $propagation, $allow)))
        $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule($system, "FullControl", $inheritance, $propagation, $allow)))
        Set-Acl -Path $Path -AclObject $acl
    } catch {
        Write-Warning "Could not restrict permissions on ${Path}: $($_.Exception.Message)"
    }
}

function Set-GitHubEnvValue {
    param([Parameter(Mandatory)][hashtable]$Values)
    if (-not $env:GITHUB_ENV) { return }
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    foreach ($key in $Values.Keys) {
        $value = [string]$Values[$key]
        if ($value.Contains("`r") -or $value.Contains("`n")) { continue }
        [System.IO.File]::AppendAllText($env:GITHUB_ENV, "$key=$value`n", $utf8)
    }
}

function Add-GitHubStepSummary {
    param([Parameter(Mandatory)][string]$Markdown)
    if (-not $env:GITHUB_STEP_SUMMARY) { return }
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::AppendAllText($env:GITHUB_STEP_SUMMARY, $Markdown + "`n", $utf8)
}

function Write-AccessBanner {
    param(
        [Parameter(Mandatory)][string]$ServerAddr,
        [Parameter(Mandatory)][int]$RemotePort,
        [string]$UserName = "RDP",
        [string]$Password = "",
        [bool]$AddSummary = $true,
        [switch]$HidePassword
    )
    $address = "$ServerAddr`:$RemotePort"
    $passwordDisplay = $Password
    if ($HidePassword) { $passwordDisplay = "******** (repository secret RDP_PASSWORD)" }

    Write-Host ""
    Write-Host "==================================================" -ForegroundColor Green
    Write-Host "  RDP ACCESS (frp)" -ForegroundColor Green
    Write-Host "    Address  : $address"
    Write-Host "    Username : $UserName"
    Write-Host "    Password : $passwordDisplay"
    Write-Host "==================================================" -ForegroundColor Green
    Write-Host ""

    if ($AddSummary) {
        $summary = @"
### RDP access (frp)

| Item | Value |
| --- | --- |
| Address | ``$address`` |
| Username | ``$UserName`` |
| Password | ``$passwordDisplay`` |
"@
        Add-GitHubStepSummary -Markdown $summary
    }
}

function Test-TcpPort {
    param(
        [Parameter(Mandatory)][string]$ComputerName,
        [Parameter(Mandatory)][int]$Port,
        [int]$TimeoutMs = 5000
    )
    $client = New-Object System.Net.Sockets.TcpClient
    try {
        $iar = $client.BeginConnect($ComputerName, $Port, $null, $null)
        if (-not $iar.AsyncWaitHandle.WaitOne($TimeoutMs, $false)) { return $false }
        $client.EndConnect($iar)
        return $true
    } catch {
        return $false
    } finally {
        $client.Close()
    }
}

function Wait-TcpPort {
    param(
        [Parameter(Mandatory)][string]$ComputerName,
        [Parameter(Mandatory)][int]$Port,
        [int]$Retries = 1,
        [int]$RetryDelaySeconds = 2,
        [int]$TimeoutMs = 4000
    )
    for ($attempt = 1; $attempt -le $Retries; $attempt++) {
        if (Test-TcpPort -ComputerName $ComputerName -Port $Port -TimeoutMs $TimeoutMs) {
            return $true
        }
        if ($attempt -lt $Retries) { Start-Sleep -Seconds $RetryDelaySeconds }
    }
    return $false
}

function Test-RdpHandshake {
    param(
        [Parameter(Mandatory)][string]$ComputerName,
        [Parameter(Mandatory)][int]$Port,
        [int]$TimeoutMs = 5000
    )
    $client = New-Object System.Net.Sockets.TcpClient
    try {
        $iar = $client.BeginConnect($ComputerName, $Port, $null, $null)
        if (-not $iar.AsyncWaitHandle.WaitOne($TimeoutMs, $false)) { return $false }
        $client.EndConnect($iar)

        $stream = $client.GetStream()
        $stream.ReadTimeout = $TimeoutMs
        $stream.WriteTimeout = $TimeoutMs

        # Minimal RDP (X.224) connection request; a healthy RDP server replies with TPKT 0x03.
        [byte[]]$probe = 0x03, 0x00, 0x00, 0x13, 0x0E, 0xE0, 0x00, 0x00, 0x00, 0x00,
                          0x00, 0x01, 0x00, 0x08, 0x00, 0x03, 0x00, 0x00, 0x00
        $stream.Write($probe, 0, $probe.Length)

        $buffer = New-Object byte[] 64
        $read = $stream.Read($buffer, 0, $buffer.Length)
        if ($read -lt 1) { return $false }
        return ($buffer[0] -eq 0x03)
    } catch {
        return $false
    } finally {
        $client.Close()
    }
}

function Wait-RdpHandshake {
    param(
        [Parameter(Mandatory)][string]$ComputerName,
        [Parameter(Mandatory)][int]$Port,
        [int]$Retries = 4,
        [int]$RetryDelaySeconds = 2,
        [int]$TimeoutMs = 5000
    )
    for ($attempt = 1; $attempt -le $Retries; $attempt++) {
        if (Test-RdpHandshake -ComputerName $ComputerName -Port $Port -TimeoutMs $TimeoutMs) {
            return $true
        }
        if ($attempt -lt $Retries) { Start-Sleep -Seconds $RetryDelaySeconds }
    }
    return $false
}

function Get-RandomRemotePort {
    param(
        [int]$Min = 30000,
        [int]$Max = 49999
    )
    if ($Max -le $Min) { throw "Invalid remote port range: $Min-$Max." }
    return (Get-Random -Minimum $Min -Maximum ($Max + 1))
}

function Get-LogTail {
    param(
        [Parameter(Mandatory)][string]$Path,
        [int]$Lines = 15
    )
    if (-not (Test-Path -LiteralPath $Path)) { return "" }
    $tail = Get-Content -LiteralPath $Path -Tail $Lines -ErrorAction SilentlyContinue
    if (-not $tail) { return "" }
    return ($tail -join [Environment]::NewLine)
}

function Get-FrpFailureKind {
    param([string]$LogText)
    if (-not $LogText) { return "unknown" }
    if ($LogText -match "(?i)authorization failed|token in login doesn't match|token is invalid|authentication failed") {
        return "auth"
    }
    if ($LogText -match "(?i)port already used|port is already used|remote port .*already") {
        return "port-conflict"
    }
    if ($LogText -match "(?i)port not allowed|not allowed to use|allowPorts|port .*not allowed") {
        return "port-denied"
    }
    if ($LogText -match "(?i)connection refused|no route to host|i/o timeout|connect to server error|dial tcp") {
        return "server-unreachable"
    }
    return "unknown"
}

function Stop-FrpcForConfig {
    param(
        [Parameter(Mandatory)][string]$ConfigPath,
        [string]$FrpcPath = ""
    )
    $stopped = $false
    try {
        $procs = Get-CimInstance -ClassName Win32_Process -Filter "Name = 'frpc.exe'" -ErrorAction Stop
        foreach ($p in $procs) {
            if ($p.CommandLine -and $p.CommandLine -like "*$ConfigPath*") {
                Stop-Process -Id $p.ProcessId -Force -ErrorAction SilentlyContinue
                $stopped = $true
            }
        }
    } catch {
        if ($FrpcPath) {
            Get-Process -Name "frpc" -ErrorAction SilentlyContinue |
                Where-Object { $_.Path -eq $FrpcPath } |
                Stop-Process -Force -ErrorAction SilentlyContinue
            $stopped = $true
        }
    }
    if ($stopped) { Start-Sleep -Milliseconds 700 }
}

function Start-FrpcProcess {
    param(
        [Parameter(Mandatory)][string]$FrpcPath,
        [Parameter(Mandatory)][string]$ConfigPath,
        [Parameter(Mandatory)][string]$LogPath
    )
    if (-not (Test-Path -LiteralPath $FrpcPath)) {
        throw "frpc.exe not found at $FrpcPath. Run Install-Frpc.ps1 first."
    }
    $logDir = Split-Path -Parent $LogPath
    if ($logDir -and -not (Test-Path -LiteralPath $logDir)) {
        New-Item -ItemType Directory -Path $logDir -Force | Out-Null
    }
    foreach ($file in @($LogPath, "$LogPath.err")) {
        if ((Test-Path -LiteralPath $file) -and ((Get-Item -LiteralPath $file).Length -gt 5MB)) {
            Move-Item -LiteralPath $file -Destination "$file.1" -Force
        }
    }

    $process = Start-Process -FilePath $FrpcPath `
        -ArgumentList @("-c", "`"$ConfigPath`"") `
        -RedirectStandardOutput $LogPath `
        -RedirectStandardError "$LogPath.err" `
        -WindowStyle Hidden `
        -PassThru

    return [pscustomobject]@{
        Process = $process
        Stdout  = $LogPath
        Stderr  = "$LogPath.err"
    }
}

function Wait-FrpProxy {
    param(
        [Parameter(Mandatory)][string]$LogPath,
        $Process,
        [int]$TimeoutSeconds = 30
    )
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    $success = $false
    while ((Get-Date) -lt $deadline) {
        if ($Process -and $Process.HasExited) { break }
        if (Test-Path -LiteralPath $LogPath) {
            $text = Get-Content -LiteralPath $LogPath -Raw -ErrorAction SilentlyContinue
            if ($text -match "start proxy success") { $success = $true; break }
            if ($text -match "(?i)start (proxy )?error|port already used|port not allowed|authorization failed|token in login doesn't match|login to server failed") { break }
        }
        Start-Sleep -Milliseconds 500
    }

    $logText = ""
    if (Test-Path -LiteralPath $LogPath) {
        $logText = Get-Content -LiteralPath $LogPath -Raw -ErrorAction SilentlyContinue
    }
    if (-not $success -and (Test-Path -LiteralPath "$LogPath.err")) {
        $errText = Get-Content -LiteralPath "$LogPath.err" -Raw -ErrorAction SilentlyContinue
        if ($errText) { $logText = "$logText`r`n$errText" }
    }

    return [pscustomobject]@{
        Success = $success
        Log     = $logText
        Exited  = [bool]($Process -and $Process.HasExited)
    }
}
